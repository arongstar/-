def sheet(wb, title, header, rows, widths=None, color='E7F0FF'):
    ws = wb.create_sheet(title)
    ws.append(header)
    for r in rows: ws.append(r)
    for c in ws[1]:
        c.font = Font(bold=True); c.fill = PatternFill('solid', fgColor=color); c.alignment = Alignment(vertical='center', wrap_text=True)
    ws.freeze_panes = 'A2'
    for i, w in enumerate(widths or []):
        ws.column_dimensions[chr(65 + i)].width = w
    return ws

def guide(wb, title, lines):
    ws = wb.active; ws.title = '사용법'
    ws['A1'] = title; ws['A1'].font = Font(bold=True, size=15)
    for i, l in enumerate(lines, start=3):
        ws.cell(row=i, column=1, value=l).alignment = Alignment(wrap_text=True, vertical='top')
    ws.column_dimensions['A'].width = 110

